const std::vector<SoundTraitWord>& soundTraitDictionary() {
    static const auto words = [] {
        std::vector<SoundTraitWord> result;
        result.reserve(groups.size() * groups.front().words.size());
        for (const auto& group : groups)
            for (const auto word : group.words)
                result.push_back({word, group.trait});
        return result;
    }();
    return words;
}

std::string_view soundTraitLabel(SoundTrait trait) noexcept {
    const auto index = static_cast<std::size_t>(trait);
    return index < groups.size() ? groups[index].label : std::string_view{};
}

std::string_view soundTraitDescription(SoundTrait trait) noexcept {
    const auto index = static_cast<std::size_t>(trait);
    return index < groups.size() ? groups[index].description : std::string_view{};
}

